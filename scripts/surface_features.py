"""How far do surface habits alone separate model outputs from the human references on the human-reference tasks?

    uv run python scripts/surface_features.py --run-id RUN [--run-id RUN2 ...]   -> reports/surface-features-v0.1.md

For every usable reference task (the same rule as the results report) this compares the human reference
with each model's outputs on three things a reader would call surface, not voice:
  markdown    the piece contains markdown a plain-text venue would show as typed: a heading, bold, a
              bullet or numbered list, or a table (the format check's own patterns);
  sentence    mean words per sentence (sentences end at . ! or ? followed by space or the end);
  length      words in the piece.
For each feature it reports the share or the median on each side and an AUROC: the probability that a
randomly chosen model output ranks above a randomly chosen human reference on that feature alone (0.5 = no
separation; for sentence length, where model text runs shorter, the AUROC is given for "shorter").
No AI-text detector is fitted, so there is nothing to tune or to overfit. Texts are prepared as the detectors
see them (the scored text), and no text is written to the report.
"""
from __future__ import annotations

import argparse
import json
import re
import statistics
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "reports" / "surface-features-v0.1.md"
SENT = re.compile(r"[.!?]+(?:\s+|$)")


def features(text: str) -> dict[str, float]:
    from humanbench.scoring.verifiers import _FORMAT_PATTERNS as FORMAT_PATTERNS

    words = len(text.split())
    sents = [s for s in SENT.split(text) if s.strip()]
    return {"markdown": float(any(p.search(text) for p in FORMAT_PATTERNS.values())),
            "sentence": words / max(1, len(sents)), "length": float(words)}


def auroc(pos: list[float], neg: list[float]) -> float:
    """P(a value from `pos` > a value from `neg`), ties counted as half."""
    wins = sum((p > n) + 0.5 * (p == n) for p in pos for n in neg)
    return wins / (len(pos) * len(neg))


def main() -> None:
    from humanbench.harness.cards import fingerprint, load_tasks, score_output, split_dir
    from humanbench.harness.report_v01 import PRIV, Judge, reference_cards, reference_judge_text

    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-id", action="append", required=True)
    a = ap.parse_args()
    cards = reference_cards(load_tasks([split_dir("ref")]), Judge())[0]
    human = [features(reference_judge_text(p)) for p in cards.values()]
    by_model: dict[str, list[dict]] = {}
    for run in a.run_id:
        for f in sorted((PRIV / "trials" / run / "raw").glob("*/*/s*.json")):
            r = json.loads(f.read_text())
            pkg = cards.get(r["task"])
            if pkg is None or r.get("infra_failure") or r.get("card_fingerprint") != fingerprint(pkg):
                continue
            text = score_output(pkg, r["output"])["scored_text"]
            if text.strip():
                by_model.setdefault(r["model"], []).append(features(text))

    def col(rows: list[dict], k: str) -> list[float]:
        return [x[k] for x in rows]

    lines = ["# Surface features on the human-reference tasks", "",
             "Generated by `scripts/surface_features.py`. It asks how far three surface habits, each on its own, "
             "separate a model's outputs from the human references written on the same content. An AUROC of 0.5 "
             "means the feature does not separate them at all; 1.0 means it separates them perfectly. The detectors "
             "separate the two far more sharply than any of these, but part of what a detector picks up may be "
             "habits like these and not anything a reader would call sounding human.", "",
             f"Human references: {len(human)}. Markdown appears in {100 * statistics.mean(col(human, 'markdown')):.0f}% of "
             f"them; median sentence {statistics.median(col(human, 'sentence')):.1f} words; median length "
             f"{statistics.median(col(human, 'length')):.0f} words.", "",
             "| model | outputs | has markdown | AUROC markdown | median words per sentence | AUROC shorter sentences | "
             "median words | AUROC longer piece |", "|---|---|---|---|---|---|---|---|"]
    for m in sorted(by_model):
        rows = by_model[m]
        lines.append(
            f"| {m} | {len(rows)} | {100 * statistics.mean(col(rows, 'markdown')):.0f}% | "
            f"{auroc(col(rows, 'markdown'), col(human, 'markdown')):.2f} | "
            f"{statistics.median(col(rows, 'sentence')):.1f} | "
            f"{auroc([-x for x in col(rows, 'sentence')], [-x for x in col(human, 'sentence')]):.2f} | "
            f"{statistics.median(col(rows, 'length')):.0f} | {auroc(col(rows, 'length'), col(human, 'length')):.2f} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
