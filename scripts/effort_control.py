"""Reasoning-effort control: does the effort a model runs at change its HumanBench score?

    uv run python scripts/effort_control.py --control RUN [--control RUN ...]   -> reports/effort-control-v0.1.md

The results ran every model at its own default reasoning effort, and the defaults differ between models. For a
control, some models were run again at another effort on a fixed random half of the public tasks, two outputs per
task. This script compares, model by model and on exactly those tasks, the two outputs from the results (samples 1
and 2, default effort) with the two control outputs. Scoring is the ledger's: an output counts if it passes the programmatic
checks, the LLM judge and the headline detector. Differences are paired by task, with a bootstrap interval
over tasks. Control runs never enter the results.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import random
import tempfile
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "reports" / "effort-control-v0.1.md"


def control_rows(runs: list[str]) -> list[dict]:
    """Ledger rows for the control runs, made by the ledger's own writer into a scratch file."""
    spec = importlib.util.spec_from_file_location("ledger", REPO / "scripts" / "ledger.py")
    ledger = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ledger)
    with tempfile.TemporaryDirectory() as tmp:
        ledger.LEDGER, ledger.CALIB = Path(tmp) / "ledger.jsonl", Path(tmp) / "calibration.json"
        ledger.write(runs)
        return [json.loads(x) for x in ledger.LEDGER.read_text().split("\n") if x.strip()]


def efforts(runs: list[str]) -> dict[tuple[str, str], str]:
    """(run, model) -> the effort recorded in the run's invocation manifests."""
    out = {}
    for run in runs:
        for p in sorted((REPO / "private" / "trials" / run / "invocations").glob("*.json")):
            for model, effort in (json.loads(p.read_text()).get("effort") or {}).items():
                out[(run, model)] = effort
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--control", action="append", required=True, help="a control run id (repeatable)")
    a = ap.parse_args()
    cal = json.loads((REPO / "reports" / "calibration-v0.1.json").read_text())
    head = next(d for d, c in cal.items() if c["headline"])
    main_rows = [json.loads(x) for x in (REPO / "reports" / "ledger-v0.1.jsonl").read_text().split("\n") if x.strip()]
    ctrl = control_rows(a.control)
    eff = efforts(a.control) | efforts(sorted({r["run"] for r in main_rows}))

    def gates(r: dict) -> tuple[float, float | None, float | None, float | None]:
        """(programmatic checks, LLM judge or None if not asked, not flagged or None if unscored, counts or None)"""
        ok = float(bool(r["scripted"]))
        fl = None if not r["scripted"] or r["floor"] is None else float(r["floor"] == 1.0)
        s = r["detectors"].get(head)
        nf = 0.0 if r["empty"] else None if s is None else float(s <= cal[head]["cutoff"])
        counts = 0.0 if not ok or fl == 0.0 or nf == 0.0 else None if fl is None or nf is None else 1.0
        return ok, fl, nf, counts

    def mean(xs: list[float]) -> float:
        return sum(xs) / len(xs) if xs else float("nan")

    lines = ["# Reasoning-effort control", "",
             "Generated by `scripts/effort_control.py`; its description says how the comparison is made. Every model "
             "in the results ran at its own default reasoning effort, and the defaults differ. Here some models were "
             "run again at another effort on a fixed random half of the public tasks, two outputs per task, and "
             "compared with their first two outputs in the results on the same tasks.", "",
             "| model | tasks | effort in the results | score | effort in the control | score | difference (control - "
             "results), 95% interval | pass programmatic checks | accepted by the LLM judge | not flagged as AI |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    unscored = 0
    for model in sorted({r["model"] for r in ctrl}):
        mine = [r for r in ctrl if r["model"] == model]
        cards = sorted({r["task"] for r in mine})
        base = [r for r in main_rows if r["model"] == model and r["task"] in set(cards) and r["sample"] <= 2]
        per = {}
        for name, rs in (("results", base), ("control", mine)):
            by = defaultdict(list)
            for r in rs:
                c = gates(r)[3]
                if c is None:
                    unscored += 1
                else:
                    by[r["task"]].append(c)
            per[name] = by
        both = [t for t in cards if per["results"].get(t) and per["control"].get(t)]
        diffs = [mean(per["control"][t]) - mean(per["results"][t]) for t in both]
        rng = random.Random(0)
        boots = sorted(mean([rng.choice(diffs) for _ in diffs]) for _ in range(2000)) if diffs else [float("nan")]
        lo, hi = boots[int(0.025 * len(boots))], boots[int(0.975 * len(boots)) - 1]

        def rate(rs: list[dict], i: int) -> str:
            xs = [g for g in (gates(r)[i] for r in rs) if g is not None]
            return f"{100 * mean(xs):.1f}%"

        e0 = ", ".join(sorted({eff.get((r["run"], model), "?") for r in base}))
        e1 = ", ".join(sorted({eff.get((r["run"], model), "?") for r in mine}))
        lines.append(
            f"| {model} | {len(both)} | {e0} | {100 * mean([mean(per['results'][t]) for t in both]):.1f}% | {e1} | "
            f"{100 * mean([mean(per['control'][t]) for t in both]):.1f}% | {100 * mean(diffs):+.1f} points "
            f"[{100 * lo:+.1f}, {100 * hi:+.1f}] | {rate(base, 0)} -> {rate(mine, 0)} | {rate(base, 1)} -> "
            f"{rate(mine, 1)} | {rate(base, 2)} -> {rate(mine, 2)} |")
    lines += ["", "The last three columns give each gate on its own, in the results and then in the control. The "
              "LLM judge is asked only about outputs that pass the programmatic checks. Scores here are on the control "
              "tasks and two outputs, so they differ from the leaderboard, which uses every task and three outputs."
              + (f" {unscored} outputs without a judge verdict or a detector score were left out." if unscored else "")]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
