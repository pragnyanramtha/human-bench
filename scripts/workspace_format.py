"""What the answer format for workspace tasks did to routing: three wordings compared.

    uv run python scripts/workspace_format.py   -> reports/workspace-format-v0.1.md

Workspace tasks show the model a fake inbox, forum or chat and ask for one or more messages. The model
has to say where each message goes. Three ways of asking were used:
  JSON           a JSON list of actions (the first results, GPT models only). Its text-free scoring rows
                 are kept in reports/workspace-json-baseline.jsonl (private ids are opaque; the mapping
                 needed to reproduce this diagnostic is in private/matrix/workspace-ids.json).
  header, first  plain drafts under a To / Replying to / Cc / Subject header. The instruction named the
                 workspace's first item id as its example of an id ("such as s01"). Outputs kept in
                 private/trials/_format_v1/.
  header, final  the same header with no example id, and "To" described as where the text ends up even
                 when it is only a draft. These are the outputs the v0.1 results use.
A routing failure is a failed routing check (ROUTING_CHECKS in the results report: required_writes,
targets, write_count and the reply, delivery and parsing checks): a required message missing or sent to
the wrong place or thread, a message to a target the card does not allow, or more messages than the
card allows. Everything is recomputed against the cards as they are now, except the JSON rows,
which are taken as scored at the time.
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PRIV = REPO / "private"
OUT = REPO / "reports" / "workspace-format-v0.1.md"
BASELINE = REPO / "reports" / "workspace-json-baseline.jsonl"

REDONE = {"a9e385acedc8436b9829340615679eef"}  # opaque id of a corrected private card; not comparable


def main() -> None:
    from humanbench.harness.cards import fingerprint, load_tasks, score_output, split_dir
    from humanbench.harness.report_v01 import ROUTING_CHECKS

    ROUTING = set(ROUTING_CHECKS)  # the same definition as the results report

    # Private ids in this workspace-only diagnostic are opaque to avoid exposing modes.
    private_ids = json.loads((PRIV / "matrix/workspace-ids.json").read_text())
    def diagnostic_id(task):
        return private_ids.get(task, task)

    tasks = {t: p for s in ("dev", "test") for t, p in load_tasks([split_dir(s)]).items() if p.env is not None}

    def judged(r: dict) -> tuple[bool, bool, bool]:
        """(routing failure, passes every scripted check, replies to the workspace's first item)"""
        pkg = tasks[r["task"]]
        res = score_output(pkg, r["output"])
        names = {f.split(":")[1].strip() for f in [*res["failures"], *res.get("task_failures", [])] if f.startswith("agent:")}
        try:
            first = any(a.in_reply_to == pkg.env.items[0].id for a in pkg.parse_agent_reply(r["output"]))
        except ValueError:
            first = False
        return bool(names & ROUTING), res["deterministic"] == 1.0, first

    pairs = defaultdict(list)  # model -> [(first wording, final wording)] for the same card and sample
    import argparse
    import shlex
    import sys
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", action="append")
    args = ap.parse_args()
    runs = args.run_id
    if not runs:
        words = shlex.split((PRIV / "report_args.txt").read_text())
        runs = [words[i + 1] for i, word in enumerate(words[:-1]) if word == "--run-id"]
    for run in runs:
        for p in sorted((PRIV / "trials" / run / "raw").glob("*/*/s*.json")):
            new = json.loads(p.read_text())
            old_path = PRIV / "trials" / "_format_v1" / run / new["model"] / new["task"] / p.name
            if (new["task"] not in tasks or diagnostic_id(new["task"]) in REDONE or new.get("infra_failure") or not old_path.is_file()
                    or new.get("card_fingerprint") != fingerprint(tasks[new["task"]])):
                continue
            old = json.loads(old_path.read_text())
            if not old.get("infra_failure"):
                pairs[new["model"]].append((judged(old), judged(new)))

    def pct(n: int, d: int) -> str:
        return f"{100 * n / d:.1f}%" if d else "–"

    lines = ["# Workspace tasks: what the answer format did to routing", "",
             "Generated by `scripts/workspace_format.py`; its docstring defines the three formats and a routing "
             "failure. The comparison is between the same model, card and sample number under each wording.", "",
             "## The GPT models under all three formats", "",
             "| format | outputs | pass every scripted check | routing failure |", "|---|---|---|---|"]
    base = [json.loads(x) for x in BASELINE.read_text().split("\n") if x.strip()]
    diagnostic_tasks = {diagnostic_id(t) for t in tasks}
    base = [r for r in base if r["task"] in diagnostic_tasks and r["task"] not in REDONE]
    lines.append(f"| JSON | {len(base)} | {pct(sum(r['scripted'] for r in base), len(base))} | "
                 f"{pct(sum(bool(ROUTING & set(r['failed_checks'])) for r in base), len(base))} |")
    gpt = [x for m, v in pairs.items() if m.startswith("gpt-") for x in v]
    for label, i in (("header, first wording", 0), ("header, final wording", 1)):
        lines.append(f"| {label} | {len(gpt)} | {pct(sum(x[i][1] for x in gpt), len(gpt))} | "
                     f"{pct(sum(x[i][0] for x in gpt), len(gpt))} |")
    lines += ["", "## Every model, first header wording against the final one", "",
              "| model | pairs | routing failure, first | routing failure, final | pass every scripted check, first | "
              "pass every scripted check, final | replies to the first item, first | replies to the first item, final |",
              "|---|---|---|---|---|---|---|---|"]
    total = Counter()
    for m in sorted(pairs):
        v = pairs[m]
        c = Counter({"n": len(v), "r0": sum(a[0] for a, _ in v), "r1": sum(b[0] for _, b in v),
                     "s0": sum(a[1] for a, _ in v), "s1": sum(b[1] for _, b in v),
                     "f0": sum(a[2] for a, _ in v), "f1": sum(b[2] for _, b in v)})
        total.update(c)
        lines.append(f"| {m} | {c['n']} | {pct(c['r0'], c['n'])} | {pct(c['r1'], c['n'])} | {pct(c['s0'], c['n'])} | "
                     f"{pct(c['s1'], c['n'])} | {pct(c['f0'], c['n'])} | {pct(c['f1'], c['n'])} |")
    c = total
    lines.append(f"| all | {c['n']} | {pct(c['r0'], c['n'])} | {pct(c['r1'], c['n'])} | {pct(c['s0'], c['n'])} | "
                 f"{pct(c['s1'], c['n'])} | {pct(c['f0'], c['n'])} | {pct(c['f1'], c['n'])} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
